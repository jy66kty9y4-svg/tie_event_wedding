import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {randomUUID} from 'node:crypto';
import {createHttpServer} from '../server/http.mjs';
import {bootstrap,execute} from '../server/service.mjs';
import {questionnaireQuestions} from '../src/questionnaire.js';

const playwrightPath=process.env.PLAYWRIGHT_MODULE_PATH||'/Users/cabinpxrn/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
const chromePath=process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const {chromium}=await import(pathToFileURL(playwrightPath));
const temporary=mkdtempSync(join(tmpdir(),'tie-client-waiting-'));
const server=createHttpServer({dbPath:join(temporary,'waiting.sqlite'),distDir:resolve('dist')});
let browser;

try{
 const {user:admin}=bootstrap(server.db,{slug:'tie',agencyName:'Студия событий',name:'Организатор',email:'admin-waiting@example.test',password:'admin-waiting-password'});
 const agency=server.db.prepare('SELECT * FROM agencies WHERE id=?').get(admin.agency_id);
 execute(server.db,admin,{id:randomUUID(),op:'settings.save',name:agency.name,version:agency.version,settings:{...JSON.parse(agency.settings),contact:'hello@agency.test'}});
 const wedding=execute(server.db,admin,{id:randomUUID(),op:'project.create',data:{name:'Анна и Иван',date:'2027-07-17'}});
 await new Promise(done=>server.listen(0,'127.0.0.1',done));
 const origin=`http://127.0.0.1:${server.address().port}`;
 browser=await chromium.launch({executablePath:chromePath,headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto(origin);
 await page.getByRole('button',{name:'Создать аккаунт',exact:true}).click();
 let dialog=page.getByRole('region', { name: 'Создать аккаунт'});
 await dialog.getByLabel('Ваше имя').fill('Анна');
 await dialog.getByLabel('Номер телефона').fill('89990000001');
 await dialog.getByLabel('Почта').fill('anna-waiting@example.test');
 await dialog.getByLabel('Пароль',{exact:true}).fill('anna-waiting-password');
 await dialog.getByRole('button',{name:'Создать аккаунт'}).click();
 await page.getByRole('heading',{name:'Ждём подтверждения администратора.'}).waitFor();
 await page.waitForURL('**/app/waiting');
 assert.equal(await page.getByRole('button',{name:'Заполнить анкету'}).count(),0);
 assert.equal(await page.getByRole('link',{name:'hello@agency.test'}).getAttribute('href'),'mailto:hello@agency.test');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.locator('body').evaluate(element=>element.scrollWidth<=element.clientWidth),true,'waiting screen overflows on mobile');
 if(process.env.TIE_WAITING_SCREENSHOTS)await page.screenshot({path:join(temporary,'waiting-mobile.png'),fullPage:true});
 const staff=await browser.newPage({viewport:{width:1280,height:900}});
 staff.on('pageerror',error=>errors.push(error.message));
 await staff.goto(origin);
 const login=staff.getByRole('region',{name:'Войти в tie'});
 await login.getByRole('button',{name:'Почта',exact:true}).click();
 await login.getByLabel('Почта',{exact:true}).fill('admin-waiting@example.test');
 await login.getByLabel('Пароль',{exact:true}).fill('admin-waiting-password');
 await login.getByRole('button',{name:'Войти',exact:true}).click();
 await staff.getByRole('button',{name:/Уведомления: /}).click();
 await staff.getByText('Новая заявка на регистрацию',{exact:false}).waitFor();
 await staff.getByRole('button',{name:'Открыть',exact:true}).click();
 await staff.waitForURL('**/app/applications?registration=*');
 await staff.getByRole('heading',{name:'Анна',exact:true}).waitFor();
 await staff.getByText('Ждёт подтверждения',{exact:true}).waitFor();
 await staff.getByRole('button',{name:'Подтвердить аккаунт',exact:true}).click();
 dialog=staff.getByRole('dialog',{name:'Подтвердить аккаунт'});
 await dialog.getByRole('combobox',{name:'Свадьба',exact:true}).selectOption(wedding.id);
 if(process.env.TIE_WAITING_SCREENSHOTS)await staff.screenshot({path:join(temporary,'approval-desktop.png'),fullPage:true});
 await dialog.getByRole('button',{name:'Подтвердить и назначить свадьбу',exact:true}).click();
 await dialog.waitFor({state:'detached'});
 await staff.getByText('Заполняет анкету',{exact:true}).waitFor();
 if(await page.getByRole('button',{name:'Проверить подтверждение'}).count())await page.getByRole('button',{name:'Проверить подтверждение'}).click();
 await page.getByRole('heading',{name:'Ваша история начинается здесь.'}).waitFor();
 assert.equal(await page.getByLabel('Дата свадьбы').count(),0);
 assert.equal(await page.locator('body').evaluate(element=>element.scrollWidth<=element.clientWidth),true,'questionnaire overflows on mobile');
 await page.getByLabel('Ваши имена').fill('Анна и Иван');
 await page.getByRole('button',{name:'← К подключению'}).click();
 await page.getByRole('heading',{name:'Ваш аккаунт подтверждён.'}).waitFor();
 await page.reload();
 await page.getByRole('heading',{name:'Ваша история начинается здесь.'}).waitFor();
 assert.equal(await page.getByLabel('Ваши имена').inputValue(),'Анна и Иван');
 const fields=await page.locator('.questionnaire-field input[required],.questionnaire-field textarea[required]').all();
 assert.equal(fields.length,questionnaireQuestions.length-1);
 for(let index=0;index<fields.length;index++)await fields[index].fill(index===0?'Анна и Иван':`Тестовый ответ ${index}`);
 await page.getByRole('checkbox',{name:'закат/рассвет'}).check();
 await page.getByRole('button',{name:'Отправить анкету и открыть кабинет'}).click();
 await page.waitForURL(`**/app/projects/${wedding.id}/finance/estimate`);
 await page.getByRole('heading',{name:'Анна и Иван',exact:true}).waitFor();
 await page.reload();
 await page.getByRole('heading',{name:'Анна и Иван',exact:true}).waitFor();
 const entry=server.db.prepare("SELECT data FROM entities WHERE kind='accountOnboarding' AND json_extract(data,'$.status')='complete'").get();
 assert.equal(Object.keys(JSON.parse(entry.data).questionnaire).length,questionnaireQuestions.length);
 await staff.reload();
 await staff.getByRole('tab',{name:/Обработанные/}).click();
 await staff.getByRole('button',{name:'Посмотреть ответы',exact:true}).click();
 await staff.getByRole('dialog',{name:'Анкета — Анна'}).getByText('Тестовый ответ 1',{exact:true}).waitFor();
 assert.deepEqual(errors,[]);
 if(process.env.TIE_WAITING_SCREENSHOTS)console.log(`Waiting screen screenshots: ${temporary}`);
 console.log('Client waiting: registration, administrator assignment, questionnaire, personal account, mobile and cold reload PASS');
}finally{
 await browser?.close();
 await new Promise(done=>server.close(done));
}
