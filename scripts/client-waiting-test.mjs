 await page.setViewportSize({width:1280,height:900});
 const fields=await page.locator('.questionnaire-field input[required],.questionnaire-field textarea[required]').all();
 assert.equal(fields.length,questionnaireQuestions.length+1);
 for(let index=0;index<fields.length;index++)await fields[index].fill(index===0?'2027-07-17':index===1?'anna-waiting@example.test':index===2?'Анна и Иван':`Тестовый ответ ${index}`);
 await page.getByRole('checkbox',{name:'закат/рассвет'}).check();
 await page.getByRole('button',{name:'Отправить анкету и заявку'}).click();
 await page.getByRole('heading',{name:'Спасибо, мы получили вашу заявку.'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Изменить анкету'}).count(),1);
 assert.equal(await page.getByRole('link',{name:'hello@agency.test'}).getAttribute('href'),'mailto:hello@agency.test');
 if(process.env.TIE_WAITING_SCREENSHOTS)await page.screenshot({path:join(temporary,'desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.locator('body').evaluate(element=>element.scrollWidth<=element.clientWidth),true,'waiting screen overflows on mobile');
 if(process.env.TIE_WAITING_SCREENSHOTS)await page.screenshot({path:join(temporary,'mobile.png'),fullPage:true});
 const application=()=>{const row=server.db.prepare("SELECT id,version,data FROM entities WHERE kind='application' ORDER BY rowid DESC LIMIT 1").get();return {...row,data:JSON.parse(row.data)};};
 let row=application();
 assert.equal(Object.keys(row.data.questionnaire).length,questionnaireQuestions.length);
 assert.equal(row.data.questionnaire.names,'Анна и Иван');
 const staff=await browser.newPage({viewport:{width:1280,height:900}});
 staff.on('pageerror',error=>errors.push(error.message));
 await staff.goto(origin);
 await staff.getByRole('button',{name:'Войти',exact:true}).click();
 const login=staff.getByRole('dialog',{name:'Войти в tie'});
 await login.getByLabel('Почта').fill('admin-waiting@example.test');
 await login.getByLabel('Пароль').fill('admin-waiting-password');
