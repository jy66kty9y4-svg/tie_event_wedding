import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';

const origin='https://tie-event.cabinpxrn.ru';
const credentials=JSON.parse(readFileSync('data/production-setup.json','utf8'));
const playwrightPath=process.env.PLAYWRIGHT_MODULE_PATH||'/Users/cabinpxrn/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
const chromePath=process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const {chromium}=await import(pathToFileURL(playwrightPath));
const browser=await chromium.launch({executablePath:chromePath,headless:true});
try{
  const context=await browser.newContext({viewport:{width:1280,height:900}});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const response=await page.goto(`${origin}/app`,{waitUntil:'networkidle'});
  assert.equal(response.status(),200);
  await page.getByRole('button',{name:'Войти',exact:true}).click();
  const login=page.getByRole('dialog',{name:'Войти в tie'});
  await login.getByLabel('Почта').fill(credentials.email);
  await login.getByLabel('Пароль').fill(credentials.password);
  await login.getByRole('button',{name:'Войти',exact:true}).click();
  await page.locator('.app-shell').waitFor();
  await page.goto(`${origin}/app/settings`,{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Настройки',exact:true}).waitFor();
  assert.equal(await page.getByLabel('Рабочее пространство').inputValue(),'organizer');
  await page.getByRole('tab',{name:'Доступ'}).click();
  await page.getByRole('searchbox',{name:'Поиск пользователей'}).fill(credentials.email);
  assert.equal(await page.locator('.user-management-row').count(),1);
  await page.getByRole('tab',{name:'Справочники'}).click();
  await page.getByRole('button',{name:'Категории подрядчиков'}).click();
  await page.getByRole('heading',{name:'Категории подрядчиков'}).waitFor();
  await page.getByRole('tab',{name:'Интеграции'}).click();
  await page.getByRole('heading',{name:'Интеграции'}).waitFor();
  await page.getByRole('tab',{name:'Сайт'}).click();
  await page.getByRole('heading',{name:'Сайт агентства'}).waitFor();
  await page.goto(`${origin}/app/applications`,{waitUntil:'networkidle'});
  await page.getByRole('tab',{name:/Новые/}).waitFor();
  await page.getByRole('tab',{name:/Обработанные/}).waitFor();
  const projectId=await page.evaluate(async()=>{
    const response=await fetch('/api/state');
    if(!response.ok)throw new Error(`Не удалось загрузить проекты: ${response.status}`);
    return (await response.json()).projects?.[0]?.id;
  });
  assert(projectId,'production account has no accessible project for budget verification');
  await page.goto(`${origin}/app/projects/${encodeURIComponent(projectId)}/finance/estimate`,{waitUntil:'networkidle'});
  await page.getByRole('searchbox',{name:'Поиск по смете'}).waitFor();
  await page.getByRole('button',{name:'Добавить раздел'}).waitFor();
  assert(await page.getByRole('button',{name:'Добавить статью'}).count()>0);
  await page.getByRole('searchbox',{name:'Поиск по смете'}).fill('___live_release_no_match___');
  await page.getByText('По вашему запросу ничего не найдено.').waitFor();
  await page.getByRole('button',{name:'Сбросить поиск'}).click();
  await page.getByRole('button',{name:'Добавить раздел'}).waitFor();
  await page.goto(`${origin}/app/projects/${encodeURIComponent(projectId)}/guests`,{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Гости',exact:true}).waitFor();
  await page.getByRole('button',{name:'Добавить гостя'}).waitFor();
  await page.getByRole('button',{name:'Колонки',exact:true}).waitFor();
  await page.locator('.guest-sheet-table').waitFor();
  await page.getByRole('columnheader',{name:/Для ссылки/}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.reload({waitUntil:'networkidle'});
  const mobileOverflow=await page.evaluate(()=>({page:document.documentElement.scrollWidth,viewport:innerWidth,wide:[...document.querySelectorAll('body *')].filter(element=>element.getBoundingClientRect().right>innerWidth+1&&!element.closest('.couple-budget-scroll')).slice(0,8).map(element=>({tag:element.tagName,className:typeof element.className==='string'?element.className:'',right:element.getBoundingClientRect().right,parent:element.parentElement?.className}))}));
  assert.equal(mobileOverflow.page>mobileOverflow.viewport,false,JSON.stringify(mobileOverflow));
  assert.deepEqual(errors,[]);
  console.log('Live release: login, settings, applications, budget, guest sheet and mobile width PASS');
}finally{await browser.close()}
