 assert.equal(await dateTabs.getByRole('tab',{name:'Актуальные 3'}).getAttribute('aria-selected'),'true');
 assert.equal(await page.locator('.project-card').count(),3);
 assert.equal(await page.locator('.project-card').filter({hasText:'Сегодня свадьба'}).count(),1);
 assert.equal(await page.locator('.project-card').filter({hasText:'Прошлая свадьба'}).count(),0);
 if(process.env.TIE_WORKSPACE_SCREENSHOTS)await page.screenshot({path:join(temporary,'projects-desktop.png'),fullPage:true});
 await dateTabs.getByRole('tab',{name:'Завершено 1'}).click();
