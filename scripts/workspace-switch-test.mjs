 assert.equal(await page.locator('.project-card').filter({hasText:'Прошлая свадьба'}).count(),1);
 await page.getByRole('textbox',{name:'Поиск свадьбы'}).fill('неизвестная пара');
 assert.equal(await page.locator('.project-card').count(),0);
 await page.getByRole('textbox',{name:'Поиск свадьбы'}).fill('');
 await dateTabs.getByRole('tab',{name:'Актуальные 3'}).click();
 assert.equal(await page.locator('.project-card').count(),3);
 await page.getByRole('button',{name:'Настройки',exact:true}).click();
 const switcher=page.getByLabel('Рабочее пространство');
 if(process.env.TIE_WORKSPACE_SCREENSHOTS)await page.screenshot({path:join(temporary,'settings-desktop.png'),fullPage:true});
 await page.getByRole('tab',{name:'Сайт'}).waitFor();
 await page.getByRole('tab',{name:'Доступ'}).click();
 await page.getByRole('searchbox',{name:'Поиск пользователей'}).fill('admin-workspaces@example.test');
 assert.equal(await page.locator('.user-management-row').count(),1);
 await page.getByRole('tab',{name:'Интеграции'}).click();
 await page.getByRole('heading',{name:'Интеграции'}).waitFor();
 await page.getByRole('tab',{name:'Справочники'}).click();
 await page.getByRole('button',{name:'Категории подрядчиков'}).click();
 await page.getByRole('heading',{name:'Категории подрядчиков'}).waitFor();
 await switcher.selectOption('couple');
 await page.waitForURL('**/app/projects');
 await page.locator('.project-card').filter({hasText:'Анна и Иван'}).locator('.project-open').click();
 await page.waitForURL(`**/app/projects/${first.id}/overview`);
 assert.equal(await page.getByLabel('Выбрать свадьбу').inputValue(),first.id);
 await page.getByLabel('Выбрать свадьбу').selectOption(second.id);
 await page.waitForURL(`**/app/projects/${second.id}/overview`);
 await page.getByRole('button',{name:'Настройки',exact:true}).click();
 await switcher.selectOption('contractor');
 await page.waitForURL('**/app/projects');
 await page.locator('.project-card').filter({hasText:'Мария и Пётр'}).locator('.project-open').click();
 await page.waitForURL(`**/app/projects/${second.id}/tasks`);
 assert.equal(await page.locator('.v2-project-tabs').getByRole('button',{name:'Финансы'}).count(),0);
 await page.getByRole('button',{name:'Настройки',exact:true}).click();
