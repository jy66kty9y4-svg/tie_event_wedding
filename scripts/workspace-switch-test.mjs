 if(process.env.TIE_WORKSPACE_SCREENSHOTS)await page.screenshot({path:join(temporary,'desktop.png'),fullPage:true});
 await page.reload();
 await switcher.waitFor();
 assert.equal(await switcher.inputValue(),'contractor');
 await switcher.selectOption('organizer');
 await page.waitForURL('**/app/today');
 assert.equal(await page.getByRole('button',{name:'Финансы агентства'}).count(),1);
 await page.goBack();
 await page.waitForURL('**/app/settings');
 assert.equal(await switcher.inputValue(),'contractor');
 await switcher.selectOption('organizer');
 await page.waitForURL('**/app/today');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Открыть навигацию'}).click();
